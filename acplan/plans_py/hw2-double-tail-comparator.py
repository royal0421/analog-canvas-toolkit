# AIC HW2 雙尾比較器（他 2026-11-11 核可的 v3 擺法）
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from acplan import Plan

p = Plan("hw2-double-tail-comparator", "../toolkit/decks/AIC-HW2_Fig1_double-tail-comparator.cir")
# 第一級：時脈控制的 PMOS 負載（閘極相對）＋差動輸入對＋尾電流源
p.pair("M3", "M4", cols=(180, 300), y=110, gates="in")
p.pair("M1", "M2", cols=(180, 300), y=300, gates="out")
p.mos("M5", 240, 390)
# 第二級：左右兩支，交叉耦合的閘極朝內
p.mos("M6", 500, 110, "R")
p.mos("M7", 700, 110, "L")
p.mos("M8", 500, 230, "L")
p.mos("M9", 700, 230, "R")
p.mos("M10", 450, 390, "L")
p.mos("M11", 550, 390, "R")
p.mos("M12", 650, 390, "L")
p.mos("M13", 750, 390, "R")
p.place("XINV1", 910, 230)
p.place("XINV2", 910, 310)
p.port_tap("clk", 240, 110, "D", lead=40, name="CLK")
p.port_pin("vip", "M1", "G")
p.port_pin("vin", "M2", "G", lead=20)
p.port_pin("clk2", "M5", "G", lead=40)
p.port_pin("vap2", "M10", "G", lead=40)
p.port_pin("van2", "M13", "G", lead=40)
# 同名標籤＝同一條 net：Vap／Van／Vsp／Vsn 標在各自橫線的外端
p.port("vap", 140, 230, "L", "Vap")
p.port("van", 770, 150, "R", "Van")
p.port("vsp", 410, 330, "L", "Vsp")
p.port("vsn", 790, 350, "R", "Vsn")
p.port_pin("inv1-in", "XINV1", "A")
p.port_pin("inv1-out", "XINV1", "Y")
p.port_pin("inv2-in", "XINV2", "A")
p.port_pin("inv2-out", "XINV2", "Y")
p.hline("tail", 340)
p.hline("vap", 230)
p.hline("van", 150)
p.hline("vsp", 330, 450, 610)
p.hline("vsn", 350, 590, 750)
p.rail(50, 150, 750)
p.route_order("clk", "tail", "p6", "p7", "vap", "van", "vsp", "vsn")
p.draw()
